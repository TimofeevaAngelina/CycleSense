enum class LegalDocumentType {
    PRIVACY_POLICY,
    TERMS_OF_USE
}

@Composable
fun PrivacyDocumentsDialog(
    documentType: LegalDocumentType,
    onDismiss: () -> Unit
) {
    val title = when (documentType) {
        LegalDocumentType.PRIVACY_POLICY -> "Политика конфиденциальности"
        LegalDocumentType.TERMS_OF_USE -> "Условия использования"
    }

    val text = when (documentType) {
        LegalDocumentType.PRIVACY_POLICY -> privacyPolicyText
        LegalDocumentType.TERMS_OF_USE -> termsOfUseText
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = {
            Text(title)
        },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = 520.dp)
                    .verticalScroll(rememberScrollState())
            ) {
                Text(
                    text = text,
                    style = MaterialTheme.typography.bodyMedium
                )
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) {
                Text("Закрыть")
            }
        }
    )
}

